    val icon: String
)

val BadgeThemes = mapOf(
    "admin" to BadgeTheme(Color(0xFFFFF7ED), Color(0xFF92400E), "crown"),
    "moderator-blue" to BadgeTheme(Color(0xFFDBEAFE), Color(0xFF1E40AF), "shield"),
