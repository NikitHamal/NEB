fun getSubjectTheme(subject: String): SubjectTheme {
    val normalized = subject.trim().lowercase()
    val key = when {
        "physics" in normalized -> "Physics"
        "chem" in normalized -> "Chemistry"
        "math" in normalized -> "Mathematics"
        "bio" in normalized -> "Biology"
        "english" in normalized -> "English"
        "nepali" in normalized -> "Nepali"
        "computer" in normalized || "programming" in normalized || "python" in normalized -> "Computer Science"
        "econom" in normalized -> "Economics"
        "account" in normalized -> "Accountancy"
        "exam" in normalized || "tip" in normalized -> "Exam Tips"
        else -> subject
    }
    return SubjectColors[key] ?: SubjectColors["General"]!!
}

fun getSubjectColor(subject: String): Color = getSubjectTheme(subject).color

