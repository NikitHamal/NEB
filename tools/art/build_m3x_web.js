/* Builds backend_python/web/static/web/js/m3x-art.js: the M3X art engine (concepts/art + concepts/art-v7 layouts) and the
   covers.json table in one cached file. Profile covers and resource thumbnails are drawn from it as inline SVG, so there is
   no image request, nothing to decode, and Light and Dark share one drawing (tones are CSS variables).
   Usage: node tools/art/build_m3x_web.js   (run export_m3x_manifest.js first when the library changes) */
var fs = require('fs'), path = require('path'), root = path.join(__dirname, '..', '..');
var out = path.join(root, 'backend_python/web/static/web/js/m3x-art.js');
var SRC = ['concepts/art/art-core.js', 'concepts/art-v7/v7-core.js', 'concepts/art/art-layouts-a.js', 'concepts/art/art-layouts-b.js', 'concepts/art-v7/v7-lay-c.js', 'concepts/art-v7/v7-lay-d.js'];
var KEEP = ['orbit', 'bauhaus', 'waves', 'scatter', 'dots', 'petals', 'mosaic', 'folds', 'tiles', 'pinwheel', 'mondrian', 'swirl', 'ripple', 'venn', 'truchet', 'contour', 'blobs', 'rings', 'bento', 'diamonds', 'segments', 'petalfield'];
var manifest = fs.readFileSync(path.join(root, 'app/src/main/assets/m3x/covers.json'), 'utf8').trim();

function strip(code) {
  return code.replace(/\/\*[\s\S]*?\*\//g, '').split('\n').map(function (l) { return l.replace(/^\s+/, '').replace(/\s+$/, ''); }).filter(Boolean).join('\n');
}
// the layouts that are never drawn (stack, net, graph, arches, ribbons, bars, capsules, cascade, bands, halftone, hills, sunset, rays)
// are cut out of the bundle by name so the file only carries what the site can show
function dropUnused(code) {
  return code.replace(/L\.(\w+) = function \(c\) \{[\s\S]*?\n  \};\n/g, function (m, name) { return KEEP.indexOf(name) > -1 ? m : ''; });
}
var engine = SRC.map(function (f) {
  var code = fs.readFileSync(path.join(root, f), 'utf8').replace(/\r/g, '');
  return strip(f.indexOf('layouts') > -1 || f.indexOf('lay-') > -1 ? dropUnused(code) : code);
}).join('\n');

var wrapper = [
  '(function (g) {',
  "var N = g.NebArt, M = " + manifest + ", TONES = ['f0','f1','f2','f3','f4','f5','f6','f7'], vars = {}, memo = {}, byId = {};",
  'M.covers.forEach(function (r) { byId[r[0]] = r; });',
  "function tone(name) { if (vars[name]) return vars[name]; var l = N.palette(name, 'light'), d = N.palette(name, 'dark'), s = '', i; for (i = 0; i < 8; i++) s += '--l' + i + ':' + l[i] + ';--d' + i + ':' + d[i] + ';'; return (vars[name] = s); }",
  'function draw(layout, palette, key, W, H, live) {',
  "  var mk = key + '|' + W + 'x' + H + (live ? 'L' : ''); if (memo[mk]) return memo[mk];",
  '  var r = N.rng(key), c = { W: W, H: H, u: Math.min(W, H), r: r, T: TONES, rr: function (a, b) { return a + (b - a) * r(); }, pick: function (a) { return a[Math.floor(r() * a.length)]; } };',
  "  var body = N.layouts[layout](c).replace(/ fill=\"f(\\d)\"/g, ' class=\"f$1\"').replace(/ stroke=\"f(\\d)\"/g, ' class=\"s$1\"');",
  "  if (live && body.length > 40000) live = false;",
  "  return (memo[mk] = '<svg class=\"m3a' + (live ? ' m3a-live' : '') + '\" viewBox=\"0 0 ' + W + ' ' + H + '\" preserveAspectRatio=\"xMidYMid slice\" aria-hidden=\"true\" focusable=\"false\" style=\"' + tone(palette) + '\"><rect class=\"f0\" width=\"' + W + '\" height=\"' + H + '\"/><g class=\"m3a-art\">' + body + '</g></svg>');",
  '}',
  'function fnv(s) { var h = 2166136261; for (var i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); } return h >>> 0; }',
  'g.NebM3x = {',
  '  ids: M.covers.map(function (r) { return r[0]; }),',
  '  has: function (id) { return !!byId[id]; },',
  "  defaultCover: function (user) { return M.covers[fnv('cover|' + (user || '')) % M.covers.length][0]; },",
  "  cover: function (id, live) { var r = byId[id] || M.covers[0]; return draw(r[1], r[2], 'cover|' + r[3] + '||' + r[1] + '|', 1200, 400, live); },",
  "  thumb: function (family, v) { var l = M.thumbs[family] || M.thumbs.GENERAL, t = l[v % l.length]; return draw(t[0], t[1], t[2], 640, 256, false); }",
  '};',
  '})(window);'
].join('\n');
var js;
js = '/* generated by tools/art/build_m3x_web.js, do not edit. M3X art v1 + v7 engine, drawn as inline SVG. */\n(function(){\nvar window = this === undefined ? self : this;\n})();\n';
js = '/* generated by tools/art/build_m3x_web.js, do not edit. M3X art v1 + v7 engine, drawn as inline SVG. */\n' + engine + '\n' + wrapper + '\n';
fs.writeFileSync(out, js);
console.log('m3x-art.js ' + js.length + ' bytes');
