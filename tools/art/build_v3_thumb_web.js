/* Builds backend_python/web/static/web/js/v3-thumb.js: the v3 art engine (core, patterns, study objects, still-life) plus the
   resource-thumbnail picker (concepts/art-v3/v3-thumb.js). Usage: node tools/art/build_v3_thumb_web.js */
var fs = require('fs'), path = require('path');
var root = path.join(__dirname, '..', '..'), d = path.join(root, 'concepts/art-v3');
var SRC = ['v3-core', 'v3-patterns', 'v3-objects-a', 'v3-objects-b', 'v3-still', 'v3-make', 'v3-thumb'];
var out = '/* generated by tools/art/build_v3_thumb_web.js, do not edit. M3X art v3 resource thumbnails, drawn as inline SVG. */\n(function(){\n';
SRC.forEach(function (f) { out += fs.readFileSync(path.join(d, f + '.js'), 'utf8').replace(/\(typeof window !== 'undefined' \? window : globalThis\)/, '(root)') + '\n'; });
out = out.replace('(function(){\n', '(function(){\nvar root = typeof window !== \'undefined\' ? window : globalThis;\n') + '})();\n';
var dest = path.join(root, 'backend_python/web/static/web/js/v3-thumb.js');
fs.writeFileSync(dest, out);
console.log('v3-thumb.js', out.length, 'bytes');
