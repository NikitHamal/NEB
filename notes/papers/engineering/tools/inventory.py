#!/usr/bin/env python3
"""Regenerate notes/papers/engineering/INVENTORY.md from files on disk + manifests.
Usage (from repo root): python3 notes/papers/engineering/tools/inventory.py"""
import os, json, glob, collections
BASE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SRC = os.path.join(BASE, 'sources')
EXT = ('.pdf', '.doc', '.docx', '.ppt', '.pptx', '.jpg', '.jpeg', '.png', '.zip', '.xls', '.xlsx')
def mb(n): return f'{n/1048576:.1f}'
rows = []
for top in sorted(os.listdir(SRC)):
    tp = os.path.join(SRC, top)
    if not os.path.isdir(tp): continue
    for sub in sorted(os.listdir(tp)):
        sp = os.path.join(tp, sub)
        files = [os.path.join(r, f) for r, _, fs in os.walk(sp) for f in fs] if os.path.isdir(sp) else [sp]
        docs = [f for f in files if f.lower().endswith(EXT)]
        pdfs = [f for f in docs if f.lower().endswith('.pdf')]
        rows.append((top, sub, len(pdfs), len(docs) - len(pdfs), sum(os.path.getsize(f) for f in files)))
st = collections.Counter()
for m in glob.glob(os.path.join(BASE, 'manifests', '*.jsonl')):
    for l in open(m):
        try: st[json.loads(l)['status'].split(':')[0]] += 1
        except Exception: pass
out = ['# Engineering papers - on-disk inventory (AUTO-GENERATED by tools/inventory.py)', '',
       f'Total PDFs: **{sum(r[2] for r in rows)}**; other docs/images: **{sum(r[3] for r in rows)}**; size: **{mb(sum(r[4] for r in rows))} MB**', '',
       f'Manifest status counts: {dict(st)}', '',
       '| source group | collection | PDFs | other docs | MB |', '|---|---|---:|---:|---:|']
out += [f'| {a} | {b} | {c} | {d} | {mb(e)} |' for a, b, c, d, e in rows]
open(os.path.join(BASE, 'INVENTORY.md'), 'w').write('\n'.join(out) + '\n')
print('\n'.join(out[:5]))
