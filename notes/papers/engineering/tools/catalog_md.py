"""catalog.json -> CATALOG.md (human index) + app/engineering-index.json (compact tree for the app).

    python3 notes/papers/engineering/tools/catalog_md.py
"""
import os, re, json, collections

HERE = os.path.dirname(os.path.abspath(__file__))
ENG = os.path.normpath(os.path.join(HERE, ".."))
recs = json.load(open(os.path.join(ENG, "catalog.json"), encoding="utf-8"))


def norm(s):
    s = re.sub(r"\b(new|old)[- ]course\b", "", s, flags=re.I)
    s = re.sub(r"[-_]+", " ", s)
    return re.sub(r"\s+", " ", s).strip().title()


def ys(rs):
    c = sorted({(r["year"] + (" " + r["season"][0] if r["season"] else "")).strip() for r in rs if r["year"]})
    return ", ".join(c) if c else "n/a"


out = ["# Engineering paper catalog (auto-generated by `tools/catalog.py` + `tools/catalog_md.py`)\n"]
total = len(recs)
unis = collections.Counter(r["university"] for r in recs)
kinds = collections.Counter(r["kind"] for r in recs)
out.append(f"**{total} papers and syllabus files** on disk under `sources/` (paths in `catalog.json`).  ")
out.append("Counts by university: " + ", ".join(f"{u} {n}" for u, n in unis.most_common()) + ".  ")
out.append("By kind: " + ", ".join(f"{k} {n}" for k, n in kinds.most_common()) + ".\n")
out.append("Formats: PDF is read-in-place; DOC/DOCX (Pokhara) need conversion before they reach the app. `n/a` = year not in the file name.\n")

index = {}
for uni in [u for u, _ in unis.most_common()]:
    rs = [r for r in recs if r["university"] == uni]
    out.append(f"\n## {uni} ({len(rs)})\n")
    bysem = collections.defaultdict(lambda: collections.defaultdict(list))
    for r in rs:
        sem = r["semester"] or "Unsorted"
        bysem[sem][norm(r["subject"]).lower()].append(r)
    index[uni] = {}
    for sem in sorted(bysem, key=lambda s: (not s.isdigit(), s)):
        subs = bysem[sem]
        label = f"Semester {sem}" if sem.isdigit() else sem
        out.append(f"\n### {label} ({sum(len(v) for v in subs.values())} files, {len(subs)} subjects)\n")
        out.append("| Subject | Files | Years / course | Kinds |\n|---|---:|---|---|")
        index[uni][label] = []
        for k in sorted(subs):
            v = subs[k]
            courses = sorted({r["course"] for r in v if r["course"]})
            kd = ", ".join(sorted({r["kind"] for r in v}))
            ycell = ys(v) if uni != "Tribhuvan University (IOE)" else (", ".join(courses) or ys(v))
            if len(ycell) > 90:
                ycell = ycell[:87] + "..."
            nm = norm(v[0]["subject"])[:70]
            out.append(f"| {nm} | {len(v)} | {ycell} | {kd} |")
            index[uni][label].append({"subject": nm, "papers": [{"id": r["id"], "path": r["path"], "year": r["year"], "season": r["season"],
                                                              "kind": r["kind"], "course": r["course"], "program": r["program"], "ext": r["ext"]} for r in v]})
open(os.path.join(ENG, "CATALOG.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
json.dump(index, open(os.path.join(ENG, "catalog-tree.json"), "w", encoding="utf-8"), ensure_ascii=False)
print("CATALOG.md lines:", len(out))
