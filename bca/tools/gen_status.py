#!/usr/bin/env python3
"""Regenerate the BCA course status block (bca/README.md, bca/course/README.md between the COURSE-STATUS
markers), bca/course/STATUS.md and the 'In this repo' column of CURRICULUM.md from books.json + the
unit files + the built PDFs.   python3 bca/tools/gen_status.py   (needs pymupdf for page counts)
"""
import json, os, re, glob
import fitz
BCA = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
C = os.path.join(BCA, "course")
reg = {k: v for k, v in json.load(open(os.path.join(C, "books.json"), encoding="utf-8")).items() if not k.startswith("_")}
bycode = {v["code"]: (k, v) for k, v in reg.items()}
ROMAN = {"I": 1, "II": 2, "III": 3, "IV": 4, "V": 5, "VI": 6, "VII": 7, "VIII": 8}


def stats(rel, meta):
    d = os.path.join(C, rel)
    units = sorted(glob.glob(os.path.join(d, "unit-*.md")))
    words = sum(len(open(u, encoding="utf-8").read().split()) for u in units)
    pdf = os.path.join(C, f"semester-{meta['semester']}", "pdfs",
                       f"NEBians-BCA-Course-Semester-{meta['semester']}-{meta['name'].replace(' ', '-').replace('/', '-')}.pdf")
    pages = len(fitz.open(pdf)) if os.path.exists(pdf) else 0
    return len(units), words, pages, os.path.relpath(pdf, C)


cur_path = os.path.join(C, "CURRICULUM.md")
lines = open(cur_path, encoding="utf-8").read().split("\n")
rows, out = [], []
for ln in lines:
    m = re.match(r"^\| (I|II|III|IV|V|VI|VII|VIII) \| (BCA \d+(?: / \d+)?) \| (.+?) \| (\d(?: \+ \d)?) \| (.*) \|$", ln)
    if m and not m.group(2).startswith("Code"):
        sem, code, name, cr, rest = m.groups(); name = name.replace("**", "")
        if code in bycode:
            rel, meta = bycode[code]
            u, w, p, pdf = stats(rel, meta)
            rows.append((ROMAN[sem], code, name, cr, "done", rel, u, w, p, pdf))
            ln = f"| {sem} | {code} | {name} | {cr} | **full book** (`{rel}`) |"
        else:
            kind = "project / internship (no notes by nature)" if re.search(r"Project|Internship", name) else ("elective slot (not written)" if "Elective" in name else "missing")
            rows.append((ROMAN[sem], code, name, cr, kind, "", 0, 0, 0, ""))
    out.append(ln)
open(cur_path, "w", encoding="utf-8").write("\n".join(out))

done = [r for r in rows if r[4] == "done"]
core_missing = [r for r in rows if r[4] == "missing"]
noteless = [r for r in rows if r[4] not in ("done", "missing")]
tw = sum(r[7] for r in done)
s4 = [r for r in done if r[0] == 4]
SEMNOTE = ("Semesters I, II, III and IV are fully done (Semester IV's Project I is a project with no notes by nature)." if len(s4) == 5 else "Semesters I, II and III are fully done." + (f" Semester IV: {len(s4)} of 5 core subjects done." if s4 else ""))
blk = [f"<!-- COURSE-STATUS -->", "## BCA course: real status", "",
       f"**{len(done)} of {len(rows)} subject slots are written, built and QA-checked; {len(core_missing)} core subjects are not started; {len(noteless)} slots are projects, internship or electives with no notes planned.** Full per-subject table: [`STATUS.md`](STATUS.md). Done so far ({tw:,} raw words of study material, counted over the unit files, including code listings and tables):",
       "", "| Sem | Code | Subject | Words | PDF pages | Status |", "|---|---|---|---|---|---|"]
for r in done:
    blk.append(f"| {r[0]} | {r[1]} | [{r[2]}](course/{r[5]}/) | {r[7]:,} | {r[8]} | done |")
blk += ["", SEMNOTE + " Everything else in `course/CURRICULUM.md` is mapped only (no notes). Nothing here has had a subject-teacher review.", "<!-- /COURSE-STATUS -->"]
block = "\n".join(blk)
for path, prefix in ((os.path.join(BCA, "README.md"), ""), (os.path.join(C, "README.md"), "course/")):
    s = open(path, encoding="utf-8").read()
    b = block if prefix == "" else block.replace("(course/", "(").replace("`course/CURRICULUM.md`", "`CURRICULUM.md`")
    s = re.sub(r"<!-- COURSE-STATUS -->.*?<!-- /COURSE-STATUS -->", lambda _m: b, s, flags=re.S)
    open(path, "w", encoding="utf-8").write(s)

st = ["# BCA course — status of every subject", "",
      "Generated by `tools/gen_status.py` from `CURRICULUM.md` (revised 2082-batch list), `books.json` and the unit files. **done** = every unit of the syllabus written, PDF built and QA-checked. **missing** = mapped in `CURRICULUM.md` only, no study material yet. Words = raw word count of the unit files (code listings and tables included).", "",
      "| Sem | Code | Subject | Cr | Status | Units | Words | PDF pages | Book / PDF |", "|---|---|---|---|---|---|---|---|---|"]
for r in rows:
    if r[4] == "done":
        st.append(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | **done** | {r[6]} | {r[7]:,} | {r[8]} | [`{r[5]}/`]({r[5]}/) · [PDF]({r[9]}) |")
    else:
        st.append(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | {r[4]} | | | | |")
st += ["", f"**Totals:** {len(done)} done · {len(core_missing)} core subjects missing · {len(noteless)} project/internship/elective slots without notes · {tw:,} raw words written."]
open(os.path.join(C, "STATUS.md"), "w", encoding="utf-8").write("\n".join(st) + "\n")
print(len(done), len(core_missing), len(noteless), tw)
for r in done: print(r[:3], r[6:9])
