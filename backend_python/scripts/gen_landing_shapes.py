#!/usr/bin/env python3
"""Generate ``web/static/web/css/landing-shapes.css``: the landing page's shape and spring tokens.

Material 3 Expressive morphs one shape into another. CSS can interpolate ``clip-path:
polygon()`` only when both polygons have the same number of points, so every shape here is
sampled at exactly N points around the centre and the page can transition between any two of
them (see ``--shape-*`` in landing.css). The spring is a damped oscillator sampled into
``linear()``, which gives buttons and tiles their overshoot without any JavaScript.

Run from backend_python/:  python3 scripts/gen_landing_shapes.py
Edit the shapes below, rerun, commit the CSS it writes. Nothing else needs to change.
"""
import math
import pathlib

N = 120
OUT = pathlib.Path(__file__).resolve().parent.parent / 'web/static/web/css/landing-shapes.css'


def lobed(k, a, phase=0.0):
    return lambda t: 1 + a * math.cos(k * t + phase)


def superellipse(n):
    return lambda t: (abs(math.cos(t)) ** n + abs(math.sin(t)) ** n) ** (-1 / n)


SHAPES = {
    'circle': lambda t: 1.0,
    'cookie': lobed(9, 0.065),
    'sunny': lobed(8, 0.11),
    'flower': lobed(5, 0.17),
    'clover': lobed(4, 0.2),
    'burst': lobed(12, 0.12),
    'squircle': superellipse(4),
    'gem': superellipse(1.55),
    'pebble': lambda t: 1 + 0.1 * math.cos(2 * t - 0.6) + 0.05 * math.cos(3 * t + 0.4),
}


def polygon(fn):
    rs = [fn(2 * math.pi * i / N - math.pi / 2) for i in range(N)]
    top = max(rs)
    pts = []
    for i, r in enumerate(rs):
        t = 2 * math.pi * i / N - math.pi / 2
        x = 50 + 50 * r / top * math.cos(t)
        y = 50 + 50 * r / top * math.sin(t)
        pts.append(f'{x:.2f}% {y:.2f}%')
    return 'polygon(' + ','.join(pts) + ')'


def spring(zeta, omega, steps=48, duration=1.0):
    """Unit step response of a damped spring, sampled for linear()."""
    wd = omega * math.sqrt(1 - zeta ** 2)
    out = []
    for i in range(steps + 1):
        t = duration * i / steps
        v = 1 - math.exp(-zeta * omega * t) * (math.cos(wd * t) + zeta * omega / wd * math.sin(wd * t))
        out.append(f'{v:.3f}'.rstrip('0').rstrip('.') or '0')
    out[-1] = '1'
    return 'linear(' + ','.join(out) + ')'


def main():
    lines = ['/* GENERATED by scripts/gen_landing_shapes.py. Do not edit by hand. */', ':root{']
    for name, fn in SHAPES.items():
        lines.append(f'--shape-{name}:{polygon(fn)};')
    # Cubic-bezier stand-ins first; browsers that know linear() (Chrome 113+, Safari 17.2+,
    # Firefox 112+) get the real springs.
    lines.append('--spring-fast:cubic-bezier(.3,1.3,.5,1);--spring:cubic-bezier(.3,1.5,.5,1);--spring-soft:cubic-bezier(.25,1.2,.4,1);')
    lines.append('}')
    lines.append('@supports (transition-timing-function:linear(0,1)){:root{')
    lines.append(f'--spring-fast:{spring(0.62, 24)};')
    lines.append(f'--spring:{spring(0.5, 15)};')
    lines.append(f'--spring-soft:{spring(0.72, 11)};')
    lines.append('}}')
    OUT.write_text('\n'.join(lines) + '\n')
    print('wrote', OUT, OUT.stat().st_size, 'bytes')


if __name__ == '__main__':
    main()
